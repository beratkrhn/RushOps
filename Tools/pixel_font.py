def trimmed(rows: list[str]) -> tuple[int, list[str]]:
    """Left offset and rows with empty columns on both sides removed."""
    width = max(len(r) for r in rows)
    padded = [r.ljust(width, ".") for r in rows]
    used = [x for x in range(width) if any(r[x] == "#" for r in padded)]
    if not used:
        return 0, ["" for _ in padded]
    left, right = used[0], used[-1]
    return left, [r[left:right + 1] for r in padded]
